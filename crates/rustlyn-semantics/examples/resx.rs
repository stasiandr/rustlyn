//! Writes the C# class that a `.resx` file stands behind.
//!
//! A resource file is not C#, and nothing in this compiler reads one. But a
//! project that has one is written as though the class already exists:
//! `CodeAnalysisResources.AbsolutePathExpected` is a property nobody typed,
//! and the build makes it. Roslyn's own build makes it with a source
//! generator shipped in a NuGet package, so a checkout on its own does not
//! have those files and 287 uses of them across the corpus resolve to
//! nothing — not because the binder failed to understand the code, but
//! because part of the input was never there.
//!
//! This writes the missing part, in the shape the generator writes it:
//!
//! ```text
//! cargo run -p rustlyn-semantics --example resx -- \
//!   Microsoft.CodeAnalysis roslyn/src/Compilers/Core/Portable/CodeAnalysisResources.resx \
//!   > generated/CodeAnalysisResources.cs
//! ```
//!
//! What it parses is the narrow part of the format that matters: the `<data>`
//! elements holding strings. A `.resx` can also carry a serialized object or
//! an icon, and those are skipped — the generator gives them a property of
//! their own type, and no compiler corpus in sight has one.

use std::path::PathBuf;

fn main() {
    let mut arguments = std::env::args().skip(1);
    let (Some(namespace), Some(path)) = (arguments.next(), arguments.next().map(PathBuf::from))
    else {
        eprintln!("usage: resx <namespace> <file.resx>");
        std::process::exit(2);
    };
    let text = std::fs::read_to_string(&path)
        .unwrap_or_else(|error| panic!("{}: {error}", path.display()));
    let class = path
        .file_stem()
        .and_then(|stem| stem.to_str())
        .unwrap_or("Resources");

    print!("{}", generate(&namespace, class, &entries(&text)));
}

/// Every `<data name="…"><value>…</value></data>` that holds a string.
///
/// The format's own documentation sits at the top of every `.resx` as a
/// comment, and it contains `<data>` examples. Skipping comments first is
/// what keeps `Color1` and `Bitmap1` out of every generated file.
fn entries(text: &str) -> Vec<(String, String)> {
    let text = without_comments(text);
    let mut found = Vec::new();
    let mut rest = text.as_str();
    while let Some(start) = rest.find("<data ") {
        rest = &rest[start + "<data ".len()..];
        let Some(head) = rest.find('>') else { break };
        let (attributes, body) = rest.split_at(head);
        rest = &body[1..];
        // An entry with a type or a MIME type holds something that is not a
        // string, and what to write for it needs that type read.
        if attributes.contains("type=") || attributes.contains("mimetype=") {
            continue;
        }
        let Some(name) = attribute(attributes, "name") else {
            continue;
        };
        let Some(value) = between(rest, "<value>", "</value>") else {
            continue;
        };
        found.push((name, unescape(value)));
    }
    found
}

fn without_comments(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(start) = rest.find("<!--") {
        out.push_str(&rest[..start]);
        match rest[start..].find("-->") {
            Some(end) => rest = &rest[start + end + "-->".len()..],
            None => return out,
        }
    }
    out.push_str(rest);
    out
}

fn attribute(attributes: &str, name: &str) -> Option<String> {
    let at = attributes.find(&format!("{name}=\""))? + name.len() + 2;
    let rest = &attributes[at..];
    Some(unescape(&rest[..rest.find('"')?]))
}

fn between<'a>(text: &'a str, open: &str, close: &str) -> Option<&'a str> {
    let start = text.find(open)? + open.len();
    let end = text[start..].find(close)? + start;
    Some(&text[start..end])
}

fn unescape(text: &str) -> String {
    text.replace("&lt;", "<")
        .replace("&gt;", ">")
        .replace("&quot;", "\"")
        .replace("&apos;", "'")
        .replace("&#xD;", "\r")
        .replace("&#xA;", "\n")
        .replace("&amp;", "&")
}

fn generate(namespace: &str, class: &str, entries: &[(String, String)]) -> String {
    let mut out = String::new();
    out.push_str("// <auto-generated/>\n\n#nullable enable\n\n");
    out.push_str(&format!("namespace {namespace}\n{{\n"));
    out.push_str(&format!(
        "    internal static partial class {class}\n    {{\n"
    ));
    out.push_str(
        "        private static global::System.Resources.ResourceManager? s_resourceManager;\n",
    );
    out.push_str(&format!(
        "        internal static global::System.Resources.ResourceManager ResourceManager => s_resourceManager ??= new global::System.Resources.ResourceManager(typeof({class}));\n"
    ));
    out.push_str(
        "        internal static global::System.Globalization.CultureInfo? Culture { get; set; }\n",
    );
    out.push_str(
        "        internal static string GetResourceString(string resourceKey, string? defaultValue = null) => ResourceManager.GetString(resourceKey, Culture) ?? defaultValue ?? resourceKey;\n",
    );
    for (name, value) in entries {
        out.push_str(&format!("        /// <summary>{}</summary>\n", doc(value)));
        out.push_str(&format!(
            "        internal static string @{name} => GetResourceString(\"{name}\");\n"
        ));
    }
    out.push_str("    }\n}\n");
    out
}

/// The resource's text as one line of a documentation comment.
fn doc(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace(['\r', '\n'], " ")
}
